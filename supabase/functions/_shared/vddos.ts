export async function fetchHtml(url: string): Promise<string> {
  let formattedUrl = url.trim();
  if (!formattedUrl.startsWith("http://") && !formattedUrl.startsWith("https://")) {
    formattedUrl = `https://${formattedUrl}`;
  }
  const response1 = await fetch(formattedUrl, { headers: browserHeaders });
  const html1 = await response1.text();
  if (html1.includes("vddosw3data") || html1.includes("R3ACTLB") || html1.includes("slowAES")) {
    console.log("vDDoS challenge detected, solving...");
    const cookie = solveVddosCookie(html1);
    if (!cookie) throw new Error("Failed to solve vDDoS challenge");
    const response2 = await fetch(formattedUrl, {
      headers: { ...browserHeaders, "Cookie": cookie },
      redirect: "follow",
    });
    if (!response2.ok) throw new Error(`HTTP ${response2.status} fetching ${formattedUrl}`);
    return await response2.text();
  }
  if (!response1.ok) throw new Error(`HTTP ${response1.status} fetching ${formattedUrl}`);
  return html1;
}