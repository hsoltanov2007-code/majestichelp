serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const body = await req.json();
    
    // Support both { message: "..." } and { messages: [...] } formats
    let message: string;
    if (body.messages && Array.isArray(body.messages)) {
      // Get the last user message from the array
      const lastUserMessage = body.messages.filter((m: any) => m.role === "user").pop();
      message = lastUserMessage?.content || "";
    } else {
      message = body.message || "";
    }

    if (!message || !message.trim()) {
      return new Response(
        JSON.stringify({ error: "Пожалуйста, введите ваш вопрос" }),
        { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    const normalizedMessage = message.toLowerCase().trim();

    // Поиск по статьям уголовного кодекса
    let foundCriminalArticles = criminalArticles.filter(a => {
      const articleLower = a.article.toLowerCase();
      const descLower = a.description.toLowerCase();
      return normalizedMessage.includes(articleLower) || 
             descLower.includes(normalizedMessage) ||
             normalizedMessage.includes(descLower.split(" ")[0]);
    });

    // Поиск по статьям административного кодекса
    let foundAdminArticles = adminArticles.filter(a => {
      const articleLower = a.article.toLowerCase();
      const descLower = a.description.toLowerCase();
      return normalizedMessage.includes(articleLower) ||
             normalizedMessage.includes(articleLower.replace(" ак", "")) ||
             descLower.includes(normalizedMessage);
    });

    // Генерация ответа
    let responseText = "";

    // Если нашли статьи УК
    if (foundCriminalArticles.length > 0) {
      responseText += "**Уголовный кодекс:**\n\n";
      foundCriminalArticles.forEach(article => {
        responseText += `**${article.article}** - ${article.description}\n`;
        responseText += `⭐ Уровень розыска: ${article.stars}\n`;
        if (article.fine) {
          responseText += `💰 Наказание: ${article.fine}\n`;
        }
        responseText += `🏛️ Требует суда: ${article.court ? "Да" : "Нет"}\n\n`;
      });
    }

    // Если нашли статьи АК
    if (foundAdminArticles.length > 0) {
      responseText += "**Административный кодекс:**\n\n";
      foundAdminArticles.forEach(article => {
        responseText += `**${article.article}** - ${article.description}\n`;
        responseText += `💰 Штраф: ${article.fine}\n\n`;
      });
    }

    // Процессуальные вопросы
    if (normalizedMessage.includes("задержан") || normalizedMessage.includes("порядок")) {
      responseText += "**Порядок задержания:**\n";
      proceduralData.detentionProcedure.forEach(step => {
        responseText += step + "\n";
      });
      responseText += "\n";
    }

    if (normalizedMessage.includes("основан") && normalizedMessage.includes("задержан")) {
      responseText += "**Основания для задержания:**\n";
      proceduralData.detentionGrounds.forEach(ground => {
        responseText += ground + "\n";
      });
      responseText += "\n";
    }

    if (normalizedMessage.includes("освобожд") || normalizedMessage.includes("отпуст")) {
      responseText += "**Основания для освобождения:**\n";
      proceduralData.releaseGrounds.forEach(ground => {
        responseText += ground + "\n";
      });
      responseText += "\n";
    }

    if (normalizedMessage.includes("субъект") || normalizedMessage.includes("кто може") || normalizedMessage.includes("присутств")) {
      responseText += "**Субъекты задержания (кто может присутствовать):**\n";
      proceduralData.detentionSubjects.forEach(subject => {
        responseText += subject + "\n";
      });
      responseText += "\n";
    }

    if (normalizedMessage.includes("миранд") || normalizedMessage.includes("права")) {
      responseText += "**Правило Миранды:**\n";
      responseText += `"${proceduralData.mirandaRights}"\n\n`;
    }

    // Если ничего не найдено
    if (!responseText) {
      responseText = "К сожалению, я не нашел информацию по вашему запросу. Попробуйте уточнить:\n\n";
      responseText += "- Номер статьи (например: '6.1', '15.1.1 ч.2', '2.1 АК')\n";
      responseText += "- Ключевые слова (например: 'убийство', 'кража', 'хулиганство')\n";
      responseText += "- Процедурные вопросы (например: 'порядок задержания', 'права Миранды', 'основания для задержания')\n\n";
      responseText += "Я могу помочь с информацией по Уголовному и Административному кодексам, а также по процессуальным нормам.";
    }

    return new Response(
      JSON.stringify({ response: responseText }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );

  } catch (error) {
    console.error("Error:", error);
    return new Response(
      JSON.stringify({ error: "Internal server error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
